import AxeBuilder from '@axe-core/playwright';
import { expect, test, type Page } from '@playwright/test';
import { createCourse, lessonText, mockBackend, openForge, openLesson } from './helpers';

/** What a screen reader or keyboard user would trip over: only the serious and critical findings of the usual WCAG A and AA rules. */
async function blockers(page: Page) {
  await page.waitForTimeout(1200); // let the screen's fade-in finish, or colours are measured half-way
  const { violations } = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze();
  return violations.filter((v) => v.impact === 'serious' || v.impact === 'critical').map((v) => `${v.id} (${v.impact}): ${v.nodes.length} element(s), e.g. ${v.nodes[0].target.join(' ')} — ${v.nodes[0].any[0]?.message ?? ''}`);
}

test('the course setup screen has no serious accessibility problems', async ({ page }) => {
  await mockBackend(page);
  await openForge(page);
  expect(await blockers(page)).toEqual([]);
});

test('a written lesson has no serious accessibility problems', async ({ page }) => {
  await mockBackend(page);
  await openForge(page);
  await createCourse(page);
  await expect(page.getByText('Generated by your AI tutor.')).toBeVisible({ timeout: 30_000 });
  await openLesson(page);
  await expect(page.getByText(lessonText).first()).toBeVisible({ timeout: 20_000 });
  expect(await blockers(page)).toEqual([]);
});
