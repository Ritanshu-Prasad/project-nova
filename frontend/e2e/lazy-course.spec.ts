import { expect, test } from '@playwright/test';
import { createCourse, lazyCourse, lessonText, mockBackend, moduleQuiz, openForge, openLesson, placement, topic } from './helpers';

test('a new course shows its progress and is ready to study', async ({ page }) => {
  await mockBackend(page);
  await openForge(page);
  await createCourse(page);
  await expect(page.getByText('Generated by your AI tutor.')).toBeVisible({ timeout: 30_000 });
  const outline = await page.evaluate(() => {
    const library = (window as any).__nova.course.getState().library;
    return Object.values(library).map((entry: any) => entry.course.modules.flatMap((m: any) => m.topics.map((t: any) => t.loaded)));
  });
  expect(outline[0].length).toBeGreaterThan(0);
  expect(outline[0].every((loaded: unknown) => loaded === false || loaded === undefined)).toBe(true);
});

test('opening a planet writes its lesson on the spot', async ({ page }) => {
  const calls = await mockBackend(page, { topicDelayMs: 6000 });
  await openForge(page);
  await createCourse(page);
  await expect(page.getByText('Generated by your AI tutor.')).toBeVisible({ timeout: 30_000 });
  await openLesson(page);
  await expect(page.getByText('Writing this lesson')).toBeVisible();
  await expect(page.getByText(lessonText).first()).toBeVisible({ timeout: 20_000 });
  expect(topic.lesson.blocks.length).toBeGreaterThan(3);
  expect(calls.topic).toBeGreaterThanOrEqual(1);
});

test('a lesson that cannot be written shows a retry and recovers', async ({ page }) => {
  await mockBackend(page, { topicFailures: 2 });
  await openForge(page);
  await createCourse(page);
  await expect(page.getByText('Generated by your AI tutor.')).toBeVisible({ timeout: 30_000 });
  await openLesson(page);
  await expect(page.getByText('NOVA could not write this lesson')).toBeVisible({ timeout: 15_000 });
  await page.getByRole('button', { name: /try again/i }).click();
  await expect(page.getByText(lessonText).first()).toBeVisible({ timeout: 15_000 });
});

test('the tutor waits for the lesson to load', async ({ page }) => {
  await mockBackend(page, { topicDelayMs: 6000 });
  await openForge(page);
  await createCourse(page);
  await expect(page.getByText('Generated by your AI tutor.')).toBeVisible({ timeout: 30_000 });
  await openLesson(page);
  await expect(page.getByText(/as soon as the lesson on/i)).toBeVisible();
  await expect(page.getByText(lessonText).first()).toBeVisible({ timeout: 15_000 });
  await expect(page.getByText(/as soon as the lesson on/i)).toBeHidden();
});

test('the module quiz is rewritten from the lessons once the last one is written', async ({ page }) => {
  const calls = await mockBackend(page);
  await openForge(page);
  await createCourse(page);
  await expect(page.getByText('Generated by your AI tutor.')).toBeVisible({ timeout: 30_000 });
  await page.evaluate(async (ids) => {
    const nova = (window as any).__nova;
    const loader = await import('/src/core/topicLoader.ts');
    const id = Object.keys(nova.course.getState().library)[0];
    await Promise.all(ids.map((topicId: string) => loader.ensureTopic(id, topicId)));
  }, lazyCourse.modules[0].topics.map((t: { id: string }) => t.id));
  await expect.poll(() => calls.moduleQuiz, { timeout: 10_000 }).toBe(1);
  await expect.poll(() => page.evaluate(() => {
    const library = (window as any).__nova.course.getState().library;
    return Object.values(library).map((entry: any) => entry.course.modules[0].quiz?.length ?? 0)[0];
  }), { timeout: 10_000 }).toBe(moduleQuiz.quiz.length);
});

test('a placement check adds where the learner starts to what they expect', async ({ page }) => {
  await mockBackend(page);
  await openForge(page);
  await page.locator('textarea').first().fill('Docker networking');
  await page.getByRole('button', { name: /not sure where you start/i }).click();
  for (let question = 1; question <= placement.questions.length; question++) {
    await expect(page.getByText(`Question ${question} of ${placement.questions.length}`)).toBeVisible();
    await page.getByRole('button', { name: placement.questions[question - 1].options[0], exact: true }).first().click();
  }
  await expect(page.getByText('Added to what you expect')).toBeVisible();
  await expect(page.locator('textarea').nth(1)).toHaveValue(/already experienced/);
});

test('when the AI service is down the app still builds a course', async ({ page }) => {
  await page.route('**/api/**', (route) => route.fulfill({ status: 503, body: '{}' }));
  await openForge(page);
  await createCourse(page);
  await expect(page.getByText(/AI service was unavailable/i)).toBeVisible({ timeout: 30_000 });
});
