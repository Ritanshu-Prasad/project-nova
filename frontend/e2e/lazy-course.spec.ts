test('the module quiz is rewritten from the lessons once the last one is written', async ({ page }) => {
  const calls = await mockBackend(page);
  await openForge(page);
  await createCourse(page);
  await expect(page.getByText('Generated by your AI tutor.')).toBeVisible({ timeout: 30_000 });
  await page.evaluate(async (ids) => {
    const nova = (window as any).__nova;
    const loader = await import('/src/core/topicLoader.ts');
    const id = Object.keys(nova.course.getState().library)[0];
    await Promise.all(ids.map((topicId: string) => loader.ensureTopic(id, topicId)));
  }, lazyCourse.modules[0].topics.map((t: { id: string }) => t.id));
  await expect.poll(() => calls.moduleQuiz, { timeout: 10_000 }).toBe(1);
  await expect.poll(() => page.evaluate(() => {
    const library = (window as any).__nova.course.getState().library;
    return Object.values(library).map((entry: any) => entry.course.modules[0].quiz?.length ?? 0)[0];
  }), { timeout: 10_000 }).toBe(moduleQuiz.quiz.length);
});

test('the plan lists every module with its topics and the learner can remove some', async ({ page }) => {
  await mockBackend(page, { course: planCourse });
  await openForge(page);
  await generatePlan(page);
  await expect(page.getByText('NOVA planned 3 planets and 6 topics')).toBeVisible();
  for (const module of planCourse.modules) {
    await expect(page.getByRole('heading', { name: module.title })).toBeVisible();
    for (const t of module.topics) await expect(page.getByText(t.title, { exact: true }).first()).toBeVisible();
  }
  const first = planCourse.modules[0].topics[0].title;
  await page.getByRole('button', { name: `Remove topic ${first}` }).first().click();
  await expect(page.getByRole('button', { name: /start course \(3 planets · 5 topics\)/i })).toBeVisible();
  await page.getByRole('button', { name: `Remove planet ${planCourse.modules[1].title}` }).click();
  await page.getByRole('button', { name: /start course \(2 planets · 3 topics\)/i }).click();
  await expect(page.getByText('Generated by your AI tutor.')).toBeVisible({ timeout: 30_000 });
  const titles = await page.evaluate(() => Object.values((window as any).__nova.course.getState().library).map((entry: any) => entry.course.modules.map((m: any) => m.title)));
  expect(titles[0]).toHaveLength(2);
  expect(titles[0]).not.toContain(planCourse.modules[1].title);
});

test('undo brings back what was removed', async ({ page }) => {
  await mockBackend(page, { course: planCourse });
  await openForge(page);
  await generatePlan(page);
  await page.getByRole('button', { name: `Remove planet ${planCourse.modules[1].title}` }).click();
  await expect(page.getByRole('heading', { name: planCourse.modules[1].title })).toHaveCount(0);
  await page.getByRole('button', { name: 'Undo' }).click();
  await expect(page.getByRole('heading', { name: planCourse.modules[1].title })).toBeVisible();
});

test('a module cannot lose its last topic one by one', async ({ page }) => {
  await mockBackend(page, { course: planCourse });
  await openForge(page);
  await generatePlan(page);
  const [one, two] = planCourse.modules[2].topics.map((t: { title: string }) => t.title);
  await page.getByRole('button', { name: `Remove topic ${one}` }).last().click();
  await expect(page.getByRole('button', { name: `Remove topic ${two}` }).last()).toBeDisabled();
});

test('a message to the chat replaces the plan', async ({ page }) => {
  const revised = JSON.parse(JSON.stringify(lazyCourse.modules[0]));
  revised.title = 'Saving for retirement';
  const calls = await mockBackend(page, { course: planCourse, revision: { reply: 'Done, I kept one module on retirement.', modules: [revised] } });
  await openForge(page);
  await generatePlan(page);
  await page.getByLabel('Ask NOVA to change the plan').fill('keep only retirement');
  await page.getByRole('button', { name: 'Send' }).click();
  await expect(page.getByText('Done, I kept one module on retirement.')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Saving for retirement' })).toBeVisible();
  await expect(page.getByRole('heading', { name: planCourse.modules[1].title })).toHaveCount(0);
  expect(calls.revise[0]).toMatchObject({ message: 'keep only retirement', title: planCourse.title });
  expect(calls.revise[0].modules).toHaveLength(3);
  await page.getByRole('button', { name: /start course \(1 planet/i }).click();
  await expect(page.getByText('Generated by your AI tutor.')).toBeVisible({ timeout: 30_000 });
});

